# Simulation
# --------------------------------------------------------------------------- #

def simulate(scenario: Optional[Scenario] = None,
             params: Optional[BridgeParams] = None,
             seed: int = 0, block_s: float = 0.5) -> BridgeSim:
    sc = scenario or Scenario()
    pr = params or BridgeParams()
    rng = np.random.default_rng(seed)

    fs, R = sc.fs, sc.oversample
    fs_i = fs * R
    nb = int(round(block_s * fs_i))
    B = int(np.ceil(sc.duration_s * fs_i / nb))
    N_i = B * nb
    t_i = np.arange(N_i) / fs_i
    h_i = t_i / sc.seconds_per_hour

    env = environment(sc, pr, rng)
    at = lambda key, h: np.interp(h, env["h"], env[key])

    # ---- loads (per unit modal mass) -----------------------------------------
    veh = _vehicle_table(sc, env, rng)
    F_traffic = _traffic_force(pr, veh, fs_i, N_i, rng)

    U_i, I_i = at("U", h_i), at("I", h_i)
    F_wind = np.zeros((N_i, pr.n_modes))
    coh = (0.4, 0.2, 0.1, 0.05)                     # effective span coherence per mode
    for n in range(pr.n_modes):
        # unit-variance turbulence with integral time L_w / U
        tau_w = 15.0 / np.maximum(U_i[::nb], 1.0)
        a = np.exp(-1.0 / (fs_i * tau_w))
        xi = _block_first_order(a, np.sqrt(1 - a ** 2),
                                rng.normal(0, 1, N_i), nb).real
        w_turb = I_i * U_i * xi
        F_wind[:, n] = (2.0 * RHO_AIR * U_i * pr.width * w_turb
                        * pr.L * coh[n % len(coh)] / pr.modal_mass)

    F_amb = rng.normal(0, pr.ambient_acc_std, (N_i, pr.n_modes))
    F_amb = np.apply_along_axis(lambda c: np.convolve(c, np.ones(3) / np.sqrt(3), "same"),
                                0, F_amb)
    F = F_traffic + F_wind + F_amb

    # ---- structure -------------------------------------------------------------
    h_b = (np.arange(B) + 0.5) * nb / fs_i / sc.seconds_per_hour
    T_b, D_b = at("T_deck", h_b), at("D", h_b)
    f_b = modal_frequencies(pr, T_b, D_b)          # (B, M)
    z_b = np.broadcast_to(np.asarray(pr.zeta), f_b.shape)

    q_i = np.zeros((N_i, pr.n_modes))
    qdd_i = np.zeros((N_i, pr.n_modes))
    for n in range(pr.n_modes):
        q, _, qdd = _modal_response(f_b[:, n], np.ascontiguousarray(z_b[:, n]),
                                    F[:, n], fs_i, nb)
        q_i[:, n], qdd_i[:, n] = q, qdd

    S = len(pr.sensor_x)
    Phi = np.array([[pr.phi(x, n + 1) for n in range(pr.n_modes)] for x in pr.sensor_x])  # (S,M)
    acc_i = qdd_i @ Phi.T
    exc_i = F @ Phi.T
    trf_i = F_traffic @ Phi.T
    wnd_i = F_wind @ Phi.T

    # ---- to the sensor rate ------------------------------------------------------
    N = int(np.floor(sc.duration_s * fs))
    acc_true = _lowpass_decimate(acc_i, R)[:N]
    q_out = _lowpass_decimate(q_i, R)[:N]
    acc = acc_true + rng.normal(0, pr.acc_noise_std, acc_true.shape)

    def rms_env(x, win_s=4.0):
        k = max(1, int(win_s * fs_i))
        ker = np.ones(k) / k
        return np.sqrt(np.apply_along_axis(lambda c: np.convolve(c ** 2, ker, "same"), 0, x))[::R][:N]

    exc_rms = rms_env(exc_i)
    force_traffic = trf_i[::R][:N]
    force_wind = wnd_i[::R][:N]

    t = np.arange(N) / fs
    hour = t / sc.seconds_per_hour
    T_deck = at("T_deck", hour)
    D = at("D", hour)
    f_nat = modal_frequencies(pr, T_deck, D)
    zeta = np.broadcast_to(np.asarray(pr.zeta), f_nat.shape).copy()
    ar_true = ar_from_modes(f_nat, zeta, fs)
    frozen = T_deck < 0.0
    damaged = D > 0.5
    regime = frozen.astype(int) + 2 * damaged.astype(int)

    # ---- event-driven side sensors -------------------------------------------
    step_h = 10 / 60
    obs_h = np.arange(step_h, sc.hours + 1e-9, step_h)
    temp_obs = dict(t=obs_h * sc.seconds_per_hour,
                    value=at("T_deck", obs_h) + rng.normal(0, 0.2, len(obs_h)))
    Uw = np.array([env["U"][(env["h"] > h - step_h) & (env["h"] <= h)].mean() for h in obs_h])
    wind_obs = dict(t=obs_h * sc.seconds_per_hour,
                    value=Uw * rng.normal(1.0, 0.05, len(obs_h)))
    wim = dict(t=veh["t"].copy(), mass=veh["mass"] * rng.normal(1.0, 0.08, len(veh["t"])),
               speed=veh["speed"].copy(), kind=veh["kind"].copy())

    return BridgeSim(
        params=pr, scenario=sc, fs=fs, t=t, hour=hour, acc=acc, acc_true=acc_true,
        q=q_out, f_nat=f_nat, zeta=zeta, ar_true=ar_true, exc_rms=exc_rms,
        force_traffic=force_traffic, force_wind=force_wind,
        U=at("U", hour), turb=at("I", hour), T_air=at("T_air", hour), T_deck=T_deck,
        traffic_rate=at("rate", hour), damage=D, regime=regime,
        vehicles=veh, temp_obs=temp_obs, wind_obs=wind_obs, wim=wim)


