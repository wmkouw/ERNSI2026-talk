def to_table(sim: BridgeSim) -> dict:
    """Flat columns (e.g. for pandas / CSV / Julia). Sensor 0 only."""
    cols = dict(t=sim.t, hour=sim.hour, acc=sim.acc[:, 0], acc_true=sim.acc_true[:, 0],
                T_deck=sim.T_deck, T_air=sim.T_air, wind=sim.U, turbulence=sim.turb,
                traffic_rate=sim.traffic_rate, exc_rms=sim.exc_rms[:, 0],
                damage=sim.damage, regime=sim.regime)
    for n in range(sim.f_nat.shape[1]):
        cols[f"f{n + 1}"] = sim.f_nat[:, n]
    for i in range(sim.ar_true.shape[1]):
        cols[f"a{i + 1}"] = sim.ar_true[:, i]
    return cols


def save_csv(sim: BridgeSim, path: str) -> str:
    cols = to_table(sim)
    np.savetxt(path, np.column_stack(list(cols.values())), delimiter=",",
               header=",".join(cols), comments="", fmt="%.7g")
    return path


def send_on_delta(t, x, delta: float):
    """Event-driven sampling: report x only when it moved by more than `delta`."""
    keep = [0]
    last = x[0]
    for k in range(1, len(x)):
        if abs(x[k] - last) > delta:
            keep.append(k)
            last = x[k]
    keep = np.asarray(keep)
    return np.asarray(t)[keep], np.asarray(x)[keep]


def psd(x, fs: float, nseg: int = 256):
    """Welch PSD (Hann, 50 % overlap). Returns (freq, power)."""
    x = np.asarray(x, float)
    nseg = min(nseg, len(x))
    step = nseg // 2
    win = np.hanning(nseg)
    segs = [x[i:i + nseg] for i in range(0, len(x) - nseg + 1, step)]
    P = np.mean([np.abs(np.fft.rfft((s - s.mean()) * win)) ** 2 for s in segs], axis=0)
    P /= fs * (win ** 2).sum()
    return np.fft.rfftfreq(nseg, 1 / fs), P


def summary(sim: BridgeSim) -> str:
    lines = [f"{sim.scenario.days}-day scenario, {sim.N} samples at {sim.fs:g} Hz "
             f"({sim.scenario.seconds_per_hour:g} s per scenario hour), "
             f"{len(sim.vehicles['t'])} vehicles"]
    for d in range(sim.scenario.days):
        s = sim.window(24 * d, 24 * (d + 1))
        a = sim.acc[s, 0]
        rms_h = np.sqrt(np.mean(a[: len(a) // 24 * 24].reshape(24, -1) ** 2, axis=1))
        lines.append(
            f"  {sim.label(24 * d)[:3]}: T_deck {sim.T_deck[s].min():5.1f}..{sim.T_deck[s].max():5.1f} C"
            f" | U max {sim.U[s].max():4.1f} m/s"
            f" | f1 {sim.f_nat[s, 0].min():.3f}..{sim.f_nat[s, 0].max():.3f} Hz"
            f" | hourly acc RMS {rms_h.min()*1e3:6.1f}..{rms_h.max()*1e3:6.1f} mm/s^2"
            f" | frozen {sim.frozen[s].mean()*24:4.1f} h")
    return "\n".join(lines)


