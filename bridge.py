def _vehicle_table(sc: Scenario, env, rng) -> dict:
    """Non-homogeneous Poisson arrivals (thinning) on the physical clock."""
    T = sc.duration_s
    lam = lambda t: np.interp(t / sc.seconds_per_hour, env["h"], env["rate"]) / 3600.0
    lam_max = env["rate"].max() / 3600.0
    n_cand = rng.poisson(lam_max * T)
    tc = np.sort(rng.uniform(0.0, T, n_cand))
    t = tc[rng.uniform(0, 1, n_cand) < lam(tc) / lam_max]
    n = len(t)

    u = rng.uniform(0, 1, n)
    kind = np.where(u < sc.truck_share, 2, np.where(u < sc.truck_share + 0.08, 1, 0))
    mass = np.where(kind == 0, 1500.0 * rng.lognormal(0, 0.15, n),
            np.where(kind == 1, 3500.0 * rng.lognormal(0, 0.15, n),
                     np.clip(22000.0 * rng.lognormal(0, 0.35, n), 9000, 44000)))
    icy = np.interp(t / sc.seconds_per_hour, env["h"], env["icy"])
    speed = (sc.speed_kmh / 3.6) * rng.normal(1.0, 0.08, n) * (1.0 - 0.25 * icy)
    speed *= np.where(kind == 2, 0.9, 1.0)
    direction = rng.choice([-1, 1], n)
    f_bounce = np.where(kind == 2, rng.uniform(1.5, 3.0, n), rng.uniform(1.2, 2.5, n))
    return dict(t=t, mass=mass, speed=speed, dir=direction, kind=kind,
                f_bounce=f_bounce, phase=rng.uniform(0, 2 * np.pi, n))


def _traffic_force(pr: BridgeParams, veh: dict, fs_i: float, N_i: int, rng):
    """Generalized traffic force per unit modal mass, shape (N_i, n_modes)."""
    M = pr.modal_mass
    F = np.zeros((N_i, pr.n_modes))
    for k in range(len(veh["t"])):
        t0, v = veh["t"][k], veh["speed"][k]
        i0 = int(np.ceil(t0 * fs_i))
        i1 = min(int(np.floor((t0 + pr.L / v) * fs_i)), N_i - 1)
        if i1 <= i0:
            continue
        tau = np.arange(i0, i1 + 1) / fs_i - t0
        x = v * tau / pr.L
        if veh["dir"][k] < 0:
            x = 1.0 - x
        rough = np.convolve(rng.normal(0, 1, len(tau) + 6), np.ones(7) / np.sqrt(7), "valid")
        bounce = (0.10 * np.exp(-tau / 1.0)
                  * np.sin(2 * np.pi * veh["f_bounce"][k] * tau + veh["phase"][k])
                  + 0.03 * rough)
        P = veh["mass"][k] * G * (1.0 + bounce) / M
        for n in range(pr.n_modes):
            F[i0:i1 + 1, n] += P * pr.phi(x, n + 1)
    return F


def _block_first_order(lam_b, gain_b, u, nb, z0=0.0):
    """z_{k+1} = lam z_k + gain u_k with block-constant coefficients.

    Vectorized within blocks, sequential across blocks. Returns z_k for all k
    (the state *before* input u_k is applied).
    """
    B = len(lam_b)
    U = u.reshape(B, nb)
    k = np.arange(nb + 1)
    lp = lam_b[:, None] ** k[None, :]                    # (B, nb+1)
    S = np.zeros((B, nb + 1), dtype=np.result_type(lam_b, u))
    S[:, 1:] = np.cumsum(U / lp[:, :nb], axis=1)
    zp = gain_b[:, None] * lp / lam_b[:, None] * S       # particular, zero init
    zp[:, 0] = 0.0
    z_init = np.empty(B, dtype=zp.dtype)
    z = z0
    for b in range(B):
        z_init[b] = z
        z = lp[b, nb] * z + zp[b, nb]
    Z = lp[:, :nb] * z_init[:, None] + zp[:, :nb]
    return Z.reshape(-1)


def _modal_response(f_hz_b, zeta_b, F, fs_i, nb):
    """Exact ZOH response of one SDOF mode with block-constant parameters.

    Uses z = q' - conj(p) q, which obeys z' = p z + F (p = -zeta w + i w_d);
    then q = Im(z)/w_d and q' = Re(z) - zeta w q. The physical state (q, q')
    is carried across blocks when the parameters change.
    """
    dt = 1.0 / fs_i
    B = len(f_hz_b)
    w = 2 * np.pi * f_hz_b
    wd = w * np.sqrt(1 - zeta_b ** 2)
    p = -zeta_b * w + 1j * wd
    lam = np.exp(p * dt)
    gain = (lam - 1.0) / p
    U = F.reshape(B, nb)
    k = np.arange(nb + 1)
    lp = lam[:, None] ** k[None, :]
    S = np.zeros((B, nb + 1), dtype=complex)
    S[:, 1:] = np.cumsum(U / lp[:, :nb], axis=1)
    zp = gain[:, None] * lp / lam[:, None] * S
    zp[:, 0] = 0.0

    q = qd = 0.0
    z_init = np.empty(B, dtype=complex)
    for b in range(B):
        z0 = qd - np.conj(p[b]) * q                 # physical state -> this block's z
        z_init[b] = z0
        z_end = lp[b, nb] * z0 + zp[b, nb]
        q = z_end.imag / wd[b]
        qd = z_end.real - zeta_b[b] * w[b] * q
    Z = lp[:, :nb] * z_init[:, None] + zp[:, :nb]
    wd_s = np.repeat(wd, nb)
    zw_s = np.repeat(zeta_b * w, nb)
    w2_s = np.repeat(w ** 2, nb)
    Z = Z.reshape(-1)
    q = Z.imag / wd_s
    qd = Z.real - zw_s * q
    qdd = -2 * zw_s * qd - w2_s * q + F
    return q, qd, qdd


def _lowpass_decimate(x, factor, cutoff_frac=0.85, taps=201):
    """Windowed-sinc anti-alias filter, then keep every `factor`-th sample."""
    if factor == 1:
        return x
    fc = cutoff_frac * 0.5 / factor              # cycles / internal sample
    n = np.arange(taps) - (taps - 1) / 2
    h = 2 * fc * np.sinc(2 * fc * n) * np.hamming(taps)
    h /= h.sum()
    y = np.apply_along_axis(lambda c: np.convolve(c, h, mode="same"), 0, x)
    return y[::factor]


