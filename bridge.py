"""
Road-bridge benchmark: a time-varying, volatile, regime-switching system.

A 30 m road bridge instrumented with one (or more) accelerometers. Its vibration
is driven by inputs that are only partly measured (traffic, wind) and modulated
by environmental and structural conditions that are never measured directly
(deck temperature, frost, damage). This is the running example for the
"critique and expand" demos:

    AR            two structural modes  <->  four AR poles
    TVAR          natural frequencies drift with deck temperature
    + HGF         excitation intensity is volatile (rush hour, storms, quiet nights)
    mixture       abrupt regimes: frozen deck (stiffer), damage (softer)

Physics (deliberately simple, but not generated by any of the demo models)
---------------------------------------------------------------------------
Modal model of a simply supported girder, modes n = 1, 2:

    q''_n + 2 zeta_n w_n(t) q'_n + w_n(t)^2 q_n = F_n(t) / M_n
    acc(x_s, t) = sum_n phi_n(x_s) q''_n(t) + sensor noise,   phi_n(x) = sin(n pi x / L)

    w_n(t) = w_n,ref * [1 + c_n (T_deck - T_ref)]          thermal drift (~0.3 %/degC)
                     * [1 + b_n sigmoid(-T_deck / width)]   frozen asphalt stiffens the deck
                     * [1 - d_n D(t)]                       damage (step at a chosen time)

Generalized forces F_n = traffic + wind buffeting + ambient micro-tremor:
  * traffic : Poisson vehicle arrivals with a weekday rate profile (rush hours),
              cars / vans / trucks, each a moving load m g (1 + bounce) phi_n(x(t));
              the bounce is excited by the expansion joint and by road roughness.
  * wind    : quasi-steady buffeting  ~ rho U B w'(t),  w' turbulence with std I*U,
              so the force variance scales like U^4 -> storms are *volatile*.
  * ambient : small broadband force so the bridge never goes silent.

Time-lapse
----------
Vibration runs in real seconds; the environment clock is compressed:
one scenario hour = `seconds_per_hour` seconds of vibration (default 30 s,
so a 5-day scenario is one hour of 20 Hz data = 72 000 samples). Instantaneous
intensities (vehicles per second, wind speed) stay physical; only their daily
evolution is sped up. The modal decay time (~5 s) is far below 30 s, so each
scenario hour is quasi-stationary, as on a real bridge.

Ground truth returned for the demos: natural frequencies, damping, the implied
AR(4) coefficients, excitation intensity, regime labels -- plus event-driven
sensor streams (deck thermometer, anemometer, weigh-in-motion vehicle events).

Only numpy is required. `python bridge.py` prints a scenario summary.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional, Tuple

import numpy as np

G = 9.81
RHO_AIR = 1.25
WEEKDAYS = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")
REGIMES = ("normal", "frozen", "damaged", "frozen + damaged")


# --------------------------------------------------------------------------- #
# Configuration
# --------------------------------------------------------------------------- #

@dataclass
class BridgeParams:
    """The structure and its sensors."""
    L: float = 30.0                                  # span [m]
    width: float = 10.0                              # deck width [m] (wind)
    mass_per_m: float = 8000.0                       # [kg/m]
    f_ref: Tuple[float, ...] = (2.0, 6.0)            # natural freqs at T_ref [Hz]
    zeta: Tuple[float, ...] = (0.015, 0.02)          # damping ratios
    T_ref: float = 10.0                              # reference deck temp [degC]
    temp_coef: Tuple[float, ...] = (-0.003, -0.002)  # rel. freq change per degC
    freeze_gain: Tuple[float, ...] = (0.10, 0.06)    # rel. freq jump when frozen
    freeze_width: float = 0.6                        # degC, sharpness of the knee
    damage_loss: Tuple[float, ...] = (0.06, 0.025)   # rel. freq loss when damaged
    sensor_x: Tuple[float, ...] = (0.3,)             # sensor positions / L
    acc_noise_std: float = 5e-4                      # accelerometer noise [m/s^2]
    ambient_acc_std: float = 8e-4                   # ambient modal force / M [m/s^2]

    @property
    def n_modes(self) -> int:
        return len(self.f_ref)

    @property
    def modal_mass(self) -> float:
        return 0.5 * self.mass_per_m * self.L

    def phi(self, x_frac, n: int):
        """Mode shape n (1-based) at position x/L."""
        return np.sin(n * np.pi * np.asarray(x_frac, float))


@dataclass
class Storm:
    day: int              # 0 = first day of the scenario
    peak_hour: float      # hour of day of the peak
    width_h: float        # std of the Gaussian bump [h]
    peak_speed: float     # extra mean wind at the peak [m/s]
    gustiness: float = 0.06   # extra turbulence intensity at the peak


@dataclass
class Scenario:
    """What happens around the bridge. Defaults: a late-autumn working week."""
    days: int = 5
    start_weekday: int = 0                 # 0 = Monday
    seconds_per_hour: float = 30.0         # time-lapse factor (see module doc)
    fs: float = 20.0                       # accelerometer sample rate [Hz]
    oversample: int = 5                    # internal rate = fs * oversample

    # temperature: daily means (at noon) and diurnal half-ranges, one per day
    temp_mean: Tuple[float, ...] = (9.0, 11.0, 3.0, -1.0, 5.0)
    temp_amp: Tuple[float, ...] = (3.0, 1.5, 5.0, 5.5, 3.0)
    temp_noise: float = 0.6                # slow weather wiggle [degC]
    deck_lag_h: float = 2.0                # thermal inertia of the deck [h]

    # wind
    wind_base: float = 3.5                 # typical mean wind [m/s]
    turb_intensity: float = 0.12           # baseline w'/U
    storms: Tuple[Storm, ...] = (Storm(day=1, peak_hour=15.0, width_h=2.5,
                                       peak_speed=13.0),)

    # traffic
    traffic_peak: float = 1500.0           # vehicles / h at the evening peak
    traffic_night: float = 50.0            # vehicles / h at 3 am
    truck_share: float = 0.08
    speed_kmh: float = 80.0
    icy_traffic_factor: float = 0.6        # fewer, slower vehicles on a frozen deck

    # damage
    damage_at_h: Optional[float] = 4 * 24 + 13.0   # scenario hour (Fri 13:00)
    damage_ramp_h: float = 0.25

    @property
    def hours(self) -> float:
        return 24.0 * self.days

    @property
    def duration_s(self) -> float:
        return self.hours * self.seconds_per_hour


# --------------------------------------------------------------------------- #
# Result container
# --------------------------------------------------------------------------- #

@dataclass
class BridgeSim:
    params: BridgeParams
    scenario: Scenario
    fs: float
    t: np.ndarray            # (N,)   physical time [s]
    hour: np.ndarray         # (N,)   scenario hour since start
    acc: np.ndarray          # (N,S)  measured acceleration [m/s^2]
    acc_true: np.ndarray     # (N,S)  noiseless acceleration
    q: np.ndarray            # (N,M)  modal displacements [m]
    f_nat: np.ndarray        # (N,M)  true natural frequencies [Hz]
    zeta: np.ndarray         # (N,M)  true damping ratios
    ar_true: np.ndarray      # (N,2M) implied AR coefficients (y_k = sum a_i y_{k-i} + e_k)
    exc_rms: np.ndarray      # (N,S)  true excitation intensity at the sensor [m/s^2]
    force_traffic: np.ndarray  # (N,S) traffic load seen by the sensor's modes [m/s^2]
    force_wind: np.ndarray     # (N,S) wind load seen by the sensor's modes [m/s^2]
    U: np.ndarray            # (N,) mean wind speed [m/s]
    turb: np.ndarray         # (N,) turbulence intensity
    T_air: np.ndarray        # (N,) [degC]
    T_deck: np.ndarray       # (N,) [degC]
    traffic_rate: np.ndarray # (N,) expected vehicles per hour
    damage: np.ndarray       # (N,) 0..1
    regime: np.ndarray       # (N,) int index into REGIMES
    vehicles: dict           # arrival table (t, mass, speed, dir, kind)
    temp_obs: dict           # deck thermometer: every 10 scenario-minutes
    wind_obs: dict           # anemometer: 10-minute means
    wim: dict                # weigh-in-motion events (noisy masses)

    @property
    def N(self) -> int:
        return len(self.t)

    @property
    def frozen(self) -> np.ndarray:
        return self.T_deck < 0.0

    def index(self, hour: float) -> int:
        return int(np.clip(round(hour * self.scenario.seconds_per_hour * self.fs),
                           0, self.N - 1))

    def window(self, h0: float, h1: float) -> slice:
        """Sample slice for scenario hours [h0, h1)."""
        return slice(self.index(h0), self.index(h1))

    def label(self, hour: float) -> str:
        """'Tue 14:20' for a scenario hour."""
        d = int(hour // 24)
        hh = hour - 24 * d
        wd = WEEKDAYS[(self.scenario.start_weekday + d) % 7]
        return f"{wd} {int(hh):02d}:{int(round((hh % 1) * 60)) % 60:02d}"


# --------------------------------------------------------------------------- #
# Environment (functions of the scenario clock)
# --------------------------------------------------------------------------- #

def _ou(n: int, dt: float, tau: float, std: float, rng) -> np.ndarray:
    a = np.exp(-dt / tau)
    e = rng.normal(0.0, std * np.sqrt(1 - a * a), n)
    x = np.empty(n)
    x[0] = rng.normal(0.0, std)
    for k in range(1, n):
        x[k] = a * x[k - 1] + e[k]
    return x


def _sigmoid(x):
    return 0.5 * (1.0 + np.tanh(0.5 * x))


def environment(sc: Scenario, pr: BridgeParams, rng, dh: float = 1 / 60):
    """Environment on a one-scenario-minute grid."""
    h = np.arange(0.0, sc.hours + dh, dh)
    hod = h % 24.0
    day = np.minimum((h // 24).astype(int), sc.days - 1)

    # --- temperature: daily means interpolated between noons + diurnal cycle
    noon = 24.0 * np.arange(sc.days) + 12.0
    mean = np.interp(h, noon, np.asarray(sc.temp_mean[:sc.days], float))
    amp = np.interp(h, noon, np.asarray(sc.temp_amp[:sc.days], float))
    T_air = mean + amp * np.cos(2 * np.pi * (hod - 15.0) / 24.0)
    T_air += _ou(len(h), dh, 3.0, sc.temp_noise, rng)
    a = np.exp(-dh / sc.deck_lag_h)
    T_deck = np.empty_like(T_air)
    T_deck[0] = T_air[0]
    for k in range(1, len(h)):
        T_deck[k] = a * T_deck[k - 1] + (1 - a) * T_air[k]

    # --- wind: afternoon breeze + storms + slow fluctuations; gusty turbulence
    U = sc.wind_base * (1.0 + 0.35 * np.cos(2 * np.pi * (hod - 15.0) / 24.0))
    storm = np.zeros_like(h)
    I = np.full_like(h, sc.turb_intensity)
    for s in sc.storms:
        bump = np.exp(-0.5 * ((h - (24.0 * s.day + s.peak_hour)) / s.width_h) ** 2)
        U += s.peak_speed * bump
        I += s.gustiness * bump
        storm = np.maximum(storm, bump)
    U *= np.exp(_ou(len(h), dh, 1.5, 0.15, rng))
    I *= np.exp(_ou(len(h), dh, 0.75, 0.25 + 0.15 * storm.max(), rng))   # gust clusters
    U = np.maximum(U, 0.3)

    # --- traffic: weekday profile, fewer vehicles in storms and on ice
    wd = (sc.start_weekday + day) % 7
    weekend = (wd >= 5).astype(float)
    prof = (np.exp(-0.5 * ((hod - 8.0) / 1.1) ** 2) * 0.9
            + np.exp(-0.5 * ((hod - 13.0) / 3.0) ** 2) * 0.45
            + np.exp(-0.5 * ((hod - 17.5) / 1.4) ** 2) * 1.0)
    prof *= (1.0 - 0.6 * weekend)
    rate = sc.traffic_night + (sc.traffic_peak - sc.traffic_night) * prof
    icy = _sigmoid(-(T_deck - 0.5) / 0.4)
    rate *= (1.0 - (1.0 - sc.icy_traffic_factor) * icy) * (1.0 - 0.3 * storm)

    # --- damage
    if sc.damage_at_h is None:
        D = np.zeros_like(h)
    else:
        D = np.clip((h - sc.damage_at_h) / max(sc.damage_ramp_h, 1e-6), 0.0, 1.0)

    return dict(h=h, T_air=T_air, T_deck=T_deck, U=U, I=I, rate=rate,
                icy=icy, storm=storm, D=D)


def modal_frequencies(pr: BridgeParams, T_deck, D):
    """True natural frequencies [Hz], shape (..., n_modes)."""
    T = np.asarray(T_deck, float)[..., None]
    D = np.asarray(D, float)[..., None]
    f = np.asarray(pr.f_ref)
    c = np.asarray(pr.temp_coef)
    b = np.asarray(pr.freeze_gain)
    d = np.asarray(pr.damage_loss)
    return (f * (1.0 + c * (T - pr.T_ref))
              * (1.0 + b * _sigmoid(-T / pr.freeze_width))
              * (1.0 - d * D))


def ar_from_modes(f_nat, zeta, fs):
    """AR coefficients implied by the modal poles: y_k = sum_i a_i y_{k-i} + e_k.

    Each mode contributes the factor (1 - 2 r cos(th) z^-1 + r^2 z^-2),
    r = exp(-zeta w / fs), th = w sqrt(1 - zeta^2) / fs.
    """
    f_nat = np.atleast_2d(f_nat)
    zeta = np.broadcast_to(zeta, f_nat.shape)
    w = 2 * np.pi * f_nat
    r = np.exp(-zeta * w / fs)
    th = w * np.sqrt(1 - zeta ** 2) / fs
    poly = np.ones((f_nat.shape[0], 1))
    for n in range(f_nat.shape[1]):
        quad = np.stack([np.ones_like(r[:, n]), -2 * r[:, n] * np.cos(th[:, n]),
                         r[:, n] ** 2], axis=1)
        out = np.zeros((poly.shape[0], poly.shape[1] + 2))
        for i in range(poly.shape[1]):
            out[:, i:i + 3] += poly[:, i:i + 1] * quad
        poly = out
    return -poly[:, 1:]


